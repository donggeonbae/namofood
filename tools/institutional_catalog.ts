function items(spec: string): Recipe["items"] {
  return spec.split(",").map((part) => {
    const m = part.trim().match(/^(.+):([\d.]+)(ml|ea)?$/);
    if (!m) throw new Error(`Invalid catalog ingredient: ${part}`);
    const item = m[1], qty = Number(m[2]), unit = m[3] || "g";
    const animal =
      /(고기|닭|오리|명태|동태|코다리|대구|가자미|삼치|고등어|갈치|조기|도미|이면수|임연수|열기|메기|아귀|오징어|주꾸미|낙지|새우|홍합|바지락|꼬막|굴|꽃게|알곤이|우럭)/
        .test(item);
    const seasoning =
      /(간장|소스|설탕|소금|식초|후추|고춧가루|고추장|된장|기름|깨|전분|가루|육수|마요네즈|^물$)/
        .test(item);
    const openedSauce = /(간장|소스|고추장|된장|마요네즈)/.test(item);
    return {
      item,
      qty,
      unit,
      storage: openedSauce
        ? "냉장"
        : seasoning
        ? "실온"
        : animal
        ? "냉동"
        : "냉장",
      loss: item === "물" ? 0 : animal ? 0.1 : seasoning ? 0.03 : 0.05,
      form: seasoning ? "가공" : "전처리",
    };
  });
}

function allergies(rows: Recipe["items"]): string {
  const text = rows.map((r) => r.item).join(" ");
  const out: string[] = [];
  for (
    const [label, pattern] of [
      ["난류", /달걀|계란|난액|마요네즈|타르타르소스/],
      ["우유", /우유|치즈|버터/],
      ["대두", /두부|콩|간장|된장|고추장|굴소스|소스/],
      ["밀", /밀가루|부침가루|튀김가루|빵가루|간장|굴소스|소스|어묵/],
      ["돼지고기", /돼지|돈육|햄|베이컨|소시지/],
      ["닭고기", /닭/],
      ["쇠고기", /소고기|쇠고기/],
      ["고등어", /고등어/],
      ["오징어", /오징어/],
      ["새우", /새우/],
      ["게", /꽃게|게살/],
      ["조개류", /(?:^|\s)굴(?:살)?(?=\s|$)|굴소스|바지락|홍합|꼬막|조갯살/],
      ["땅콩", /땅콩/],
      ["호두", /호두/],
      ["토마토", /토마토|케첩/],
    ] as const
  ) if (pattern.test(text)) out.push(label);
  return out.join(", ");
}

