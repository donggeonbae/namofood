function main(
  method: string,
  protein: string,
  seasoning: string,
  menu: string,
  core: string,
  sauce: string,
  prep: string,
  cooking: Cooking,
  cold = false,
) {
  add(
    menu,
    "main",
    method,
    protein,
    seasoning,
    [core, sauce].filter(Boolean).join(","),
    prep,
    cooking,
    cold,
  );
}
function soup(
  menu: string,
  core: string,
  base: string,
  prep: string,
  cooking: Cooking,
  protein = "vegetable",
) {
  add(
    menu,
    "soup",
    "boil",
    protein,
    base === DOENJANG ? "doenjang" : "broth",
    `${core},${base}`,
    prep,
    cooking,
  );
}
function side(
  method: string,
  menu: string,
  core: string,
  sauce: string,
  prep: string,
  cooking: Cooking,
  cold = false,
) {
  add(
    menu,
    "side",
    method,
    "vegetable",
    cold ? "seasoned" : "plain",
    `${core},${sauce}`,
    prep,
    cooking,
    cold,
  );
}

